VERSION = "qam64-rect-snapshot-v2"
HASH = "d" * 64


def qam_frame(capture_id="qam64-1", *, seed=39, random_payload=False):
    if random_payload:
        rng = np.random.default_rng(20261024)
        choices = np.array(list(R.all_64_symbols().values()), dtype=complex)
        syms = rng.choice(choices, size=128)
        raw = np.resize(np.repeat(syms, R.SPS), R.REFERENCE_SAMPLES)
        wire = np.empty((len(raw), 2), dtype="<i2")
        wire[:, 0] = np.rint(raw.real * 10).astype(np.int16)
        wire[:, 1] = np.rint(raw.imag * 10).astype(np.int16)
        payload = wire.tobytes()
    else:
        payload, _ = R.make_frame_bytes(seed, phase_deg=23.0, iq_order="QI")
    return RxIqFrame(
        capture_id=capture_id, payload=payload, samples=4096,
        sample_rate_hz=60_000_000, ratio=0, daemon_timestamp_ns=123,
        connection_generation=2, config_revision=5, request_id=9,
        release_id=H.RELEASE, op="rx.capture", physical=False,
        pre_readback=RxReadback(io_ok=True),
        post_readback=RxReadback(io_ok=True),
        completed_at_monotonic=time.monotonic())


def submitted():
    draft = dict(expected_mode="QAM64", symrate_hz=3_000_000, shaping="RECT",
                 reference_enabled=True, reference_seed=39, decim=1,
                 rx_len=4096, input_fs_hz=60_000_000)
    return P.freeze_qam64_demod_config(draft, 7, iq_order="QI")


def prepared(frames):
    client = H.FakeCaptureClient(blocked=False, samples=4096)
    queue = list(frames)

    def capture(args, physical=False):
        client.calls.append(("capture", dict(args), bool(physical)))
        return queue.pop(0)
    client.capture = capture
    worker = W.RfStatusWorker(client, poll_interval=100)
    worker._demod_checked = True
    worker._demod_pipeline = None
    worker._qpsk_pipeline = None
    worker._rrc_pipeline = None
    worker._qam64_pipeline = P
    worker._demod_info = dict(
        available=False, qpsk_available=False, rrc_available=False,
        qam64_available=True, release_id=H.RELEASE, reason="QAM64 ready",
        algorithm_version=None, algorithm_sha256=None,
        qpsk_algorithm_version=None, qpsk_algorithm_sha256=None,
        rrc_algorithm_version=None, rrc_algorithm_sha256=None,
        qam64_algorithm_version=VERSION, qam64_algorithm_sha256=HASH)
    return client, worker, submitted()


def test_worker_qam64_submission_binds_same_frame_and_denominator():
    client, worker, sub = prepared([qam_frame("qam64-good")])
    assert worker.demod_status()["qam64_available"] is True
    assert worker.demod_status()["qam64_algorithm_version"] == VERSION
    reply = worker.submit_capture(dict(samples=4096, ratio=0),
                                  demod_config=sub, demod_revision=7)
    assert reply["queued"]
    payload, status = H.drain(worker)
    assert status["state"] == W.RX_CAPTURE_DONE
    env = payload["demod_result"]
    assert isinstance(env, P.Qam64Envelope)
    assert env.submitted == sub
    assert env.result.capture_id == payload["frame"]["capture_id"] == "qam64-good"
    assert env.result.reason == ""
    assert (env.result.bit_errors, env.result.compared_bits) == (0, 384)
    assert env.result.ber == 0.0
    assert env.result.valid_symbols == 127
    assert env.result.alignment_bits == 378
    assert env.result.comparison_start_symbol == 63
    assert env.result.evm_available is False and env.result.evm_rms is None


def test_worker_second_frame_does_not_keep_old_ber():
    client, worker, sub = prepared([
        qam_frame("good"), qam_frame("bad", random_payload=True)])
    assert worker.submit_capture(dict(samples=4096, ratio=0), demod_config=sub)["queued"]
    first, _ = H.drain(worker)
    assert first["demod_result"].result.ber == 0.0
    assert worker.submit_capture(dict(samples=4096, ratio=0), demod_config=sub)["queued"]
    second, status = H.drain(worker)
    result = second["demod_result"].result
    assert status["state"] == W.RX_CAPTURE_DONE
    assert result.capture_id == "bad"
    assert result.reason == "REFERENCE_NOT_FOUND"
    assert result.reference_sync is not True
    assert result.bit_errors is None and result.compared_bits is None
    assert result.ber is None


def test_worker_config_rejected_when_qam64_pipeline_absent():
    client, worker, sub = prepared([qam_frame()])
    worker._qam64_pipeline = None
    reply = worker.submit_capture(dict(samples=4096, ratio=0), demod_config=sub)
    assert reply.get("queued") is None and reply["code"] == "DEMOD_UNAVAILABLE"
    assert worker.capture_status()["state"] == W.RX_CAPTURE_IDLE


def test_worker_stop_after_stop_is_stopped():
    client, worker, sub = prepared([qam_frame()])
    worker._stop.set()
    reply = worker.submit_capture(dict(samples=4096, ratio=0), demod_config=sub)
    assert reply["code"] == "STOPPED"


def test_worker_cancel_discards_result_and_keeps_close_semantics():
    client = H.FakeCaptureClient(blocked=True, samples=4096)
    worker = W.RfStatusWorker(client, poll_interval=100)
    worker._demod_checked = True
    worker._demod_pipeline = None
    worker._qam64_pipeline = P
    worker._qam64_pipeline = P
    worker._demod_info = dict(qam64_available=True, release_id=H.RELEASE,
                              qam64_algorithm_version=VERSION,
                              qam64_algorithm_sha256=HASH)
    reply = worker.submit_capture(dict(samples=4096, ratio=0), demod_config=submitted())
    assert reply["queued"]
    assert client.entered.wait(2)
    worker.cancel_capture()
    client.release.set()
    payload, status = H.drain(worker)
    assert payload is None
    assert status["state"] == W.RX_CAPTURE_CANCELLED
    assert status["cancelled"] is True


