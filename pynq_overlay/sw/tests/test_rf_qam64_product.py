def _fake_demod_release(tmp_path, monkeypatch, contract):
    import merged_release as R
    tmp_path.mkdir(parents=True, exist_ok=True)
    names = ("rf_bpsk_pipeline.py", "rf_bpsk_receiver.py",
             "rf_qpsk_pipeline.py", "rf_qpsk_receiver.py",
             "rf_rrc_pipeline.py", "rf_rrc_receiver.py",
             "rf_qam16_pipeline.py", "rf_qam16_receiver.py",
             "rf_qam64_pipeline.py", "rf_qam64_receiver.py",
             "rf_modem_result.py")
    for name in names:
        (tmp_path / name).write_text("# fake\n", encoding="utf-8")
    modules = {}
    for name in names:
        stem = name[:-3]
        version = {"rf_bpsk_receiver.py": "bpsk-rect-snapshot-v2",
                   "rf_qpsk_receiver.py": "qpsk-rect-snapshot-v1",
                   "rf_rrc_receiver.py": "rrc-alpha035-sps20-v3",
                   "rf_qam16_receiver.py": "qam16-rect-snapshot-v1",
                   "rf_qam64_receiver.py": VERSION}.get(name, "v1")
        modules[stem] = types.SimpleNamespace(
            __name__=stem, __file__=str(tmp_path / name), VERSION=version)
    manifest = dict(
        release_id="fake-qam64-release", software_contract=contract,
        software={"rf_bpsk_receiver.py": "a" * 64,
                  "rf_qpsk_receiver.py": "b" * 64,
                  "rf_rrc_receiver.py": "c" * 64,
                  "rf_qam16_receiver.py": "d" * 64,
                  "rf_qam64_receiver.py": "e" * 64})
    monkeypatch.setattr(R, "verify_release",
                        lambda directory, require_software=True: manifest)
    monkeypatch.setattr(W.importlib, "import_module", lambda name: modules[name])
    worker = W.RfStatusWorker(H.FakeCaptureClient(blocked=False), poll_interval=100)
    worker._release_directory = tmp_path
    worker._ensure_demod()
    return worker


def test_worker_contract_gate_adds_qam64_only_to_new_contract(tmp_path, monkeypatch):
    old = _fake_demod_release(tmp_path / "rrc", monkeypatch,
                              "cnn-bpsk-modrec4-qpsk-rrc-v1")
    assert old.demod_status()["rrc_available"] is True
    assert old.demod_status()["qam64_available"] is False
    new = _fake_demod_release(tmp_path / "qam", monkeypatch,
                              "cnn-bpsk-modrec4-qpsk-rrc-qam16-qam64-v1")
    assert new.demod_status()["qam64_available"] is True
    assert new.demod_status()["qam64_algorithm_version"] == VERSION
