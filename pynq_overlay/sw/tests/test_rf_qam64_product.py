def ui_payload(a):
    frame = dataclasses.replace(qam_frame("qam64-ui"), release_id="release")
    sub = a.rx_demod_submission()
    assert isinstance(sub, P.Qam64DemodConfig)
    assert sub.iq_order == "QI"
    a.rx_capture_submitted()
    return dict(frame=frame.to_dict(), analysis=summarize(frame),
                demod_result=P.analyze_qam64(frame, sub))


