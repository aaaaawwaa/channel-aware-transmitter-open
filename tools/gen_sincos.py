#!/usr/bin/env python3
"""Generate a 1024 x 16-bit signed sin/cos ROM as Verilog (src/rtl/sincos_rom.v).

Self-checks: quadrant zero crossings, positive/negative peaks, and sin^2+cos^2
constant to within the 16-bit quantisation floor.

Same layout as tools/gen_sine.py (4 entries per row, self-check then print OK),
because the I/Q rotator's phase resolution is what sets the rotator's spurious
floor: 2*pi/1024 ~ 0.35 deg, about -49 dB, which is well below the 8-bit signal's
own quantisation floor (~-50 dB).
"""
import math

N = 1024
AMPL = 32767
OUT = "src/rtl/sincos_rom.v"
OUT_H = "sdk/src/sincos_q15.h"

cos_v = [round(AMPL * math.cos(2.0 * math.pi * i / N)) for i in range(N)]
sin_v = [round(AMPL * math.sin(2.0 * math.pi * i / N)) for i in range(N)]

lines = [
    "// Auto-generated by tools/gen_sincos.py - do not edit manually",
    "`timescale 1ns / 1ps",
    "// 1024 点 x 16 位有符号 sin/cos 双输出, 同步读。32 Kbit 必须落块 RAM:",
    "// 用 LUTRAM 会吃掉约 16K LUT(见设计文档 2.2 节)。",
    "module sincos_rom (",
    "    input  wire               clk,",
    "    input  wire [9:0]         addr,",
    "    output reg  signed [15:0] cos_out,",
    "    output reg  signed [15:0] sin_out",
    ");",
    '    (* ram_style = "block" *) reg signed [15:0] cos_mem [0:1023];',
    '    (* ram_style = "block" *) reg signed [15:0] sin_mem [0:1023];',
    "    initial begin",
]
for i in range(0, N, 4):
    lines.append("        " + " ".join(
        f"cos_mem[{j:4d}] = 16'sh{cos_v[j] & 0xFFFF:04X};" for j in range(i, i + 4)
    ))
for i in range(0, N, 4):
    lines.append("        " + " ".join(
        f"sin_mem[{j:4d}] = 16'sh{sin_v[j] & 0xFFFF:04X};" for j in range(i, i + 4)
    ))
lines += [
    "    end",
    "    always @(posedge clk) begin",
    "        cos_out <= cos_mem[addr];",
    "        sin_out <= sin_mem[addr];",
    "    end",
    "endmodule",
]
with open(OUT, "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")

# 同一张表再出一份 C 头, 给 PS 固件做 I/Q 矩阵合成用。
# 固件不能依赖 libm(app 的链接行里没有 -lm), 而矩阵合成需要 cos/sin;
# 固件按"表 + 线性插值"取角, 插值误差约 (2*pi/1024)^2/8 = 4.7e-6 rad,
# 折算到 Q2.14 系数上约 0.08 LSB, 远低于系数本身的 1 LSB —— 不会成为瓶颈。
# 两份输出共用同一组 cos_v/sin_v, 所以 RTL 与固件不可能分叉。
hlines = [
    "/* Auto-generated by tools/gen_sincos.py - do not edit manually.",
    " *",
    " * 1024-point Q1.15 sin/cos tables, same values as src/rtl/sincos_rom.v.",
    " * Used by the PS firmware to compose the I/Q impairment matrix; the",
    " * firmware takes angles by table lookup + linear interpolation because",
    " * the app does not link libm.",
    " */",
    "#ifndef SINCOS_Q15_H",
    "#define SINCOS_Q15_H",
    "",
    "#define SINCOS_Q15_N 1024",
    "",
    "static const short sincos_q15_cos[SINCOS_Q15_N] = {",
]
for i in range(0, N, 8):
    hlines.append("    " + " ".join(f"{cos_v[j]:6d}," for j in range(i, i + 8)))
hlines += ["};", "", "static const short sincos_q15_sin[SINCOS_Q15_N] = {"]
for i in range(0, N, 8):
    hlines.append("    " + " ".join(f"{sin_v[j]:6d}," for j in range(i, i + 8)))
hlines += ["};", "", "#endif /* SINCOS_Q15_H */"]
with open(OUT_H, "w", encoding="utf-8") as f:
    f.write("\n".join(hlines) + "\n")

# self-check
assert cos_v[0] == AMPL and sin_v[0] == 0, "origin wrong"
assert cos_v[256] == 0 and sin_v[256] == AMPL, "quarter turn wrong"
assert cos_v[512] == -AMPL and sin_v[512] == 0, "half turn wrong"
assert cos_v[768] == 0 and sin_v[768] == -AMPL, "three-quarter turn wrong"
worst = max(abs(cos_v[i] ** 2 + sin_v[i] ** 2 - AMPL * AMPL)
            for i in range(N)) / float(AMPL * AMPL)
assert worst < 1e-3, f"sin^2+cos^2 not constant: {worst:.2e}"
print(f"OK: {OUT} + {OUT_H} written, {N} entries x2, "
      f"self-check passed (max |1-r^2| {worst:.2e})")
