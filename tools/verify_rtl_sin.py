assert len(rtl) == 256, f"RTL table has {len(rtl)} entries, expected 256"

def to_signed(v):
    return v if v < 128 else v - 256

# Full comparison
mismatches = []
for i in range(256):
    if rtl[i] != expected[i]:
        mismatches.append((i, rtl[i], expected[i]))

print("=== RTL sine table vs math.sin(2*pi*i/256) ===")
print(f"Mismatches: {len(mismatches)} out of 256")
if mismatches:
    print("\nAll mismatches:")
    for i, r, e in mismatches:
        s_r = to_signed(r)
        s_e = to_signed(e)
        print(f"  addr[{i:3d}]: RTL=0x{r:02X}({s_r:+4d}) expected=0x{e:02X}({s_e:+4d}) err={s_r-s_e:+d}")

# Key sample points
key_addrs = [0, 1, 63, 64, 65, 127, 128, 129, 191, 192, 193, 255]
print("\n=== Key sample points ===")
for a in key_addrs:
    s_r = to_signed(rtl[a])
    s_e = to_signed(expected[a])
    match = "MATCH" if rtl[a] == expected[a] else f"MISMATCH (err={s_r-s_e})"
    print(f"  addr[{a:3d}]: RTL=0x{rtl[a]:02X}({s_r:+4d}) expected=0x{expected[a]:02X}({s_e:+4d})  {match}")

# Check symmetry
print("\n=== Symmetry checks ===")
# Half-wave: sin(i+128) should be -sin(i)
sym_errors = 0
for i in range(128):
    v1 = to_signed(rtl[i])
    v2 = to_signed(rtl[(i+128) % 256])
    if v1 != -v2:
        sym_errors += 1
        if sym_errors <= 3:
            print(f"  Half-wave symmetry FAIL at i={i}: sin[{i}]={v1:+d} sin[{i+128}]={v2:+d}")
print(f"Half-wave symmetry errors: {sym_errors} (expected 0)")

# Quadrant symmetry
q_errors = 0
for i in range(64):
    v1 = to_signed(rtl[i])
    v2 = to_signed(rtl[128 - i])
    if v1 != v2:
        q_errors += 1
        if q_errors <= 3:
            print(f"  Quad symmetry FAIL at i={i}: sin[{i}]={v1:+d} sin[{128-i}]={v2:+d}")
print(f"Quadrant symmetry errors: {q_errors} (expected 0)")

print("\n=== Conclusion ===")
if len(mismatches) == 0:
    print("RTL sine table PERFECTLY matches mathematical sin table.")
else:
    print(f"RTL sine table has {len(mismatches)} deviations from math.sin.")
