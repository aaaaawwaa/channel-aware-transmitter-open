static void ddr_service(void)
{
    XTime now;
    if (!ddr_active) return;
    read_user_status();
    XTime_GetTime(&now);
    dma_last_status = XAxiDma_ReadReg(Dma.RegBase + XAXIDMA_TX_OFFSET, XAXIDMA_SR_OFFSET);
    if (dma_last_status & XAXIDMA_ERR_ALL_MASK) {
        if (!ddr_stop_transfer())
            ddr_error_code = 0x21u;
        else
            ddr_error_code = 0x23u;
        ddr_dma_state = "ERROR";
    } else if (user_underflow) {
        if (!ddr_stop_transfer())
            ddr_error_code = 0x21u;
        else
            ddr_error_code = 0x25u;
        ddr_dma_state = "ERROR";
    } else if (strcmp(ddr_dma_state, "DRAIN") == 0 && user_stream_done) {
        dma_stream_ctrl(0, 0);
        ddr_active = 0;
        ddr_dma_state = "READY";
        ddr_error_code = 0;
    } else if (strcmp(ddr_dma_state, "RUNNING") == 0 &&
               (dma_last_status & XAXIDMA_IRQ_IOC_MASK) &&
               !XAxiDma_Busy(&Dma, XAXIDMA_DMA_TO_DEVICE)) {
        XAxiDma_IntrAckIrq(&Dma, XAXIDMA_IRQ_IOC_MASK, XAXIDMA_DMA_TO_DEVICE);
        ddr_dma_state = "DRAIN";
    } else if ((now - ddr_started_at) > DMA_TIMEOUT_TICKS) {
        if (!ddr_stop_transfer())
            ddr_error_code = 0x21u;
        else
            ddr_error_code = 0x24u;
        ddr_dma_state = "ERROR";
    }
}
