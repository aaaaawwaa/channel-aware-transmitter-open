static int parse_u32_limit(const char *s, u32 *out, u32 limit)
{
    u32 v = 0;
    if (*s == '\0') return 0;
    while (*s) {
        u32 digit;
        if (*s < '0' || *s > '9') return 0;
        digit = (u32)(*s - '0');
        if (v > (limit - digit) / 10u) return 0;
        v = v * 10u + digit;
        s++;
    }
    *out = v;
    return 1;
}

static int parse_u32(const char *s, u32 *out)
{
    return parse_u32_limit(s, out, 2000000u);
}

static int parse_long(const char *s, long *out)
{
    long v = 0;
    int neg = 0;
    if (*s == '-') { neg = 1; s++; }
    else if (*s == '+') { s++; }
    if (*s == '\0') return 0;
    while (*s) {
        if (*s < '0' || *s > '9') return 0;
        v = v * 10 + (*s - '0');
        if (v > 1000000) return 0;
        s++;
    }
    *out = neg ? -v : v;
    return 1;
}

