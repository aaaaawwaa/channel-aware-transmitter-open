/*****************************************************************************
 * AC820 AWG bridge (PS bare-metal, runs from OCM, no DDR).
 * UART1 (MIO48/49) @115200, 8N1. ASCII line protocol, CR/LF terminated.
 *   SET CH1|CH2 WAVE SINE|SQUARE|TRIANGLE|SAW|PULSE|NOISE -> OK
 *   SET CH1|CH2 DUTY <0..100>                    -> OK (PULSE 高电平占空比)
 *   SET CH1|CH2 FREQ <10..1000000>              -> OK
 *   SET CH1|CH2 AMPL <0..100>                   -> OK
 *   SET CH1|CH2 MODE OFF|AM|FM|PM|SWEEP         -> OK
 *   SET CH1|CH2 MODWAVE SINE|SQUARE|TRIANGLE|SAW -> OK
 *   SET CH1|CH2 MODFREQ <1..500000>             -> OK  (0.1Hz 单位)
 *   SET CH1|CH2 AMDEPTH <0..100>                -> OK
 *   SET CH1|CH2 FMDEV <0..500000>               -> OK
 *   SET CH1|CH2 PMDEV <0..511>                  -> OK
 *   SET CH2 PHASE <0..36000>                    -> OK  (0.01° 单位, 仅 CH2)
 *   SET CH2 PHASELINK ON|OFF                    -> OK  (仅 CH2, 联动使能)
 *   SET DIGMOD MODE OFF|BPSK|QPSK|QAM4|QAM16|QAM64 -> OK
 *   SET DIGMOD FILTER RECT|RRC                   -> OK (仅 STOPPED; RRC 支持全部模式)
 *   SET DIGMOD ROLLOFF 0.2|0.35|0.5             -> OK (仅 STOPPED)
 *   SET DIGMOD SYMRATE <10..1000000>             -> OK (仅 STOPPED)
 *   SET DIGMOD SEED <1..127>                     -> OK (仅 STOPPED)
 *   SET DIGMOD RESET                            -> OK (仅 STOPPED)
 *   GET CH1|CH2                                 -> CHx WAVE .. DUTY .. FREQ .. AMPL ..
 *   GET DIGMOD                                  -> DIGMOD MODE <name> SOURCE PRBS7 FILTER <name> ROLLOFF <name> SEED <n> SYMRATE <Hz> STATE <state>
 *   SET DDR CLEAR                                -> OK (stage upload)
 *   SET DDR CHUNK <offset> <hex> <crc8>          -> OK (max 20 bytes)
 *   SET DDR COMMIT <bit_length> <crc16>          -> OK
 *   SET DDR ABORT                                -> OK
 *   SET DDR START|STOP                           -> OK
 *   SET DDR PP CLEAR                             -> OK
 *   SET DDR PP CHUNK <bank> <offset> <hex> <crc8> -> OK
 *   SET DDR PP COMMIT <bank> <bit_length> <crc16> -> OK
 *   SET DDR PP START|STOP                        -> OK
 *   SET DDR PP STOP                              -> OK
 *   SET DDR CAPACITY TEST                        -> DDR CAPACITY ..
 *   GET DDR                                     -> DDR VALID .. BUFFER .. MAX .. LENGTH .. CRC .. UPLOAD .. ACTIVE .. DMA .. ERROR ..
 *   GET DDR PP                                  -> DDR PP ACTIVE .. ACTIVE_BANK .. NEXT_BANK .. STATE .. ERROR ..
 *   GET DMA                                     -> DMA BASE ... STATE ...
 *   SET DMA TEST                                -> DMA TEST PASS ...
 *   SET DMA BENCH                               -> DMA BENCH PASS ...
 * Errors: ERR UNKNOWN CMD / ERR BAD CHANNEL / ERR BAD FIELD / ERR BAD VALUE
 *         ERR FREQ OUT OF RANGE / ERR AMPL OUT OF RANGE / ERR TIMEOUT
 *         ERR MODE OUT OF RANGE / ERR MODWAVE OUT OF RANGE / ERR MODFREQ OUT OF RANGE
 *         ERR AMDEPTH OUT OF RANGE / ERR FMDEV OUT OF RANGE / ERR PMDEV OUT OF RANGE
 *         ERR PHASE OUT OF RANGE / ERR SYMRATE OUT OF RANGE / ERR SEED OUT OF RANGE / ERR DIGMOD RUNNING
 * Writes per-channel params to AXI GPIO (dual 32-bit all-output):
 *   word  = freq | ampl<<20 | wave<<28  (matches PL reg_bridge packing)
 *   wordC = am_depth<<24 | mfreq<<5 | mwave<<3 | mode
 *   wordD = pm_dev<<19 | fm_dev
 *   wordE = CH2 相位差 (32 位全周期, 0.01°×2^32/36000, gpio10)
 *   wordF = phaselink | pulse_duty_ch1<<1 | pulse_duty_ch2<<9 | digmod_mode<<17
 *            | digmod_filter<<20 | digmod_rolloff<<21 | digmod_seed<<23
 *   GPIO11[29:23] = DIGMOD PRBS7 seed (1..127)
 *   GPIO11[22:21] = DIGMOD ROLLOFF (00=0.35, 01=0.2, 10=0.5)
 *   GPIO11[20]    = DIGMOD FILTER (0=RECT, 1=RRC)
 *   GPIO11[19:17] = global DIGMOD mode (wordF)
 *   GPIO12[31:0] = DIGMOD symbol phase step (symrate × 2^32 / 50 MHz)
 *****************************************************************************/
