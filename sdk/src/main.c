/* IEEE CRC-32 (reflected 0xEDB88320, init 0xFFFFFFFF, final xor) used to
 * validate UDP DATA payloads and a completed bank before COMMIT. */
static u32 ddr_pp_crc32(const u8 *data, u32 len)
{
    static u32 table[256];
    static int tab_init;
    u32 crc = 0xffffffffu;
    u32 i;
    if (!tab_init) {
        u32 n, k;
        for (n = 0; n < 256u; n++) {
            u32 r = n;
            for (k = 0; k < 8u; k++)
                r = (r >> 1u) ^ (0xedb88320u & (0u - (r & 1u)));
            table[n] = r;
        }
        tab_init = 1;
    }
    for (i = 0; i < len; i++)
        crc = table[(crc ^ data[i]) & 0xffu] ^ (crc >> 8u);
    return ~crc;
}

/* First contiguous missing 4-byte word in [0, total_bytes); when the whole
 * bank is present, report offset == total_bytes and length == 0. */
static void ddr_pp_udp_missing_range(u32 bank, u32 total_bytes,
                                     u32 *off, u32 *len)
{
    u32 words = total_bytes / 4u;
    u32 c = ddr_pp_contig_words[bank];
    u32 j;
    if (c > words) c = words;
    *off = c * 4u;
    *len = 0;
    if (c >= words)
        return;                              /* fully received: off==total, len==0 */
    if (ddr_pp_hwm_words[bank] <= c) {       /* nothing received past the hole */
        *len = (words - c) * 4u;             /* tail is one missing run, O(1) */
        return;
    }
    j = c;                                   /* received data exists past hole */
    while (j < words &&
           !(ddr_pp_stage_seen[bank][j >> 3] & (u8)(1u << (j & 7u))))
        j++;
    *len = (j - c) * 4u;
}

static int ddr_pp_udp_bank_complete(u32 bank, u32 bytes)
{
    u32 words = bytes / 4u;
    u32 i;
    if (bank > 1u || (bytes & 3u) || bytes == 0u || bytes > DDR_PP_BANK_BYTES)
        return 0;
    for (i = 0; i < words; i++)
        if (!(ddr_pp_stage_seen[bank][i >> 3] & (u8)(1u << (i & 7u))))
            return 0;
    return 1;
}

static int ddr_pp_udp_begin(u16 bank, u32 total_bytes, u32 payload_crc32)
{
    if (bank > 1u || !ddr_pp_layout_valid() || total_bytes == 0u ||
        (total_bytes & 3u) || total_bytes > DDR_PP_BANK_BYTES)
        return UDP_DDR_PP_ERROR_RANGE;
    /* While a bank plays, the other bank is the only legal refill target;
     * while stopped, keep the first-release rule (digital mod off, no play). */
    if (ddr_active || ddr_uploading ||
        ddr_pp_stage_owner[0] == DDR_PP_STAGE_UART ||
        ddr_pp_stage_owner[1] == DDR_PP_STAGE_UART)
        return UDP_DDR_PP_ERROR_BUSY;
    if (ddr_pp_active) {
        if (bank == ddr_pp_active_bank)
            return UDP_DDR_PP_ERROR_BUSY;
    } else if (digmod_mode != 0u || play_blocks_config()) {
        return UDP_DDR_PP_ERROR_BUSY;
    }
    if (ddr_pp_stage_owner[bank] != DDR_PP_STAGE_NONE)
        return UDP_DDR_PP_ERROR_BUSY;
    /* Clear only this bank's staging metadata. The other bank's bitmap,
     * length, CRC, validity, and owner are never touched here. */
    memset(ddr_pp_stage_seen[bank], 0, DDR_PP_STAGE_BITMAP_BYTES);
    ddr_pp_stage_bytes[bank] = 0;
    ddr_pp_stage_open[bank] = 0;
    ddr_pp_stage_owner[bank] = DDR_PP_STAGE_UDP;
    ddr_pp_stage_expected_bytes[bank] = total_bytes;
    ddr_pp_stage_received_bytes[bank] = 0;
    ddr_pp_contig_words[bank] = 0;
    ddr_pp_hwm_words[bank] = 0;
    ddr_pp_payload_crc32[bank] = payload_crc32;
    ddr_pp_udp_committed[bank] = 0;
    ddr_pp_bit_length[bank] = 0;
    ddr_pp_crc16[bank] = 0;
    ddr_pp_valid[bank] = 0;
    ddr_pp_bank_fresh[bank] = 0u;
    return UDP_DDR_PP_ERROR_NONE;
}

static int ddr_pp_udp_write(u16 bank, u32 offset, const u8 *data, u16 length)
{
    UINTPTR base;
    u32 first, words, i;
    if (bank > 1u || (offset & 3u) || length == 0u ||
        length > 1400u || (length & 3u) ||
        (u32)offset + (u32)length > ddr_pp_stage_expected_bytes[bank] ||
        ddr_pp_stage_owner[bank] != DDR_PP_STAGE_UDP ||
        !ddr_pp_layout_valid())
        return UDP_DDR_PP_ERROR_RANGE;
    base = ddr_pp_bank_addr(bank);
    first = offset / 4u;
    words = (u32)length / 4u;
    /* An already-received word that differs from DDR is a conflict; reject the
     * whole datagram without writing a single new byte. */
    for (i = 0; i < words; i++) {
        u32 w = first + i;
        if (ddr_pp_stage_seen[bank][w >> 3] & (u8)(1u << (w & 7u))) {
            if (memcmp((const void *)(base + (UINTPTR)w * 4u),
                       data + i * 4u, 4u) != 0)
                return UDP_DDR_PP_ERROR_CONFLICT;
        }
    }
    /* Write only unreceived words; count each new word exactly once. */
    for (i = 0; i < words; i++) {
        u32 w = first + i;
        if (!(ddr_pp_stage_seen[bank][w >> 3] & (u8)(1u << (w & 7u)))) {
            memcpy((void *)(base + (UINTPTR)w * 4u), data + i * 4u, 4u);
            ddr_pp_stage_seen[bank][w >> 3] |= (u8)(1u << (w & 7u));
            ddr_pp_stage_received_bytes[bank] += 4u;
            if (w + 1u > ddr_pp_hwm_words[bank])
                ddr_pp_hwm_words[bank] = w + 1u;
        }
    }
    ddr_pp_advance_contig(bank, ddr_pp_stage_expected_bytes[bank] / 4u);
    return UDP_DDR_PP_ERROR_NONE;
}

static int ddr_pp_udp_commit(u16 bank, u32 total_bytes, u32 payload_crc32)
{
    UINTPTR addr;
    u32 computed;
    if (bank > 1u || !ddr_pp_layout_valid() ||
        ddr_pp_stage_owner[bank] != DDR_PP_STAGE_UDP ||
        ddr_pp_stage_expected_bytes[bank] != total_bytes ||
        ddr_pp_payload_crc32[bank] != payload_crc32)
        return UDP_DDR_PP_ERROR_SESSION;
    if (ddr_pp_stage_received_bytes[bank] != total_bytes ||
        !ddr_pp_udp_bank_complete(bank, total_bytes))
        return UDP_DDR_PP_ERROR_INCOMPLETE;
    addr = ddr_pp_bank_addr(bank);
    computed = ddr_pp_crc32((const u8 *)addr, total_bytes);
    if (computed != payload_crc32)
        return UDP_DDR_PP_ERROR_CRC;
    ddr_pp_flush_cpu_write_range(addr, total_bytes);
    ddr_pp_bit_length[bank] = total_bytes * 8u;
    ddr_pp_crc16[bank] = crc16_ccitt((const u8 *)addr, total_bytes);
    ddr_pp_stage_owner[bank] = DDR_PP_STAGE_NONE;
    ddr_pp_stage_expected_bytes[bank] = 0;
    ddr_pp_stage_received_bytes[bank] = 0;
    ddr_pp_contig_words[bank] = 0;
    ddr_pp_hwm_words[bank] = 0;
    ddr_pp_stage_bytes[bank] = 0;
    ddr_pp_stage_open[bank] = 0;
    ddr_pp_udp_committed[bank] = 1;
    if (!ddr_pp_active) {
        ddr_pp_state = "IDLE";
        ddr_pp_error_code = 0;
    }
    ddr_pp_valid[bank] = 1;   /* last metadata mutation: only now is it playable */
    ddr_pp_bank_fresh[bank] = 1u;
    return UDP_DDR_PP_ERROR_NONE;
}

static void ddr_pp_udp_abort(u16 bank)
{
    if (bank > 1u || ddr_pp_stage_owner[bank] != DDR_PP_STAGE_UDP)
        return;
    memset(ddr_pp_stage_seen[bank], 0, DDR_PP_STAGE_BITMAP_BYTES);
    ddr_pp_stage_owner[bank] = DDR_PP_STAGE_NONE;
    ddr_pp_stage_expected_bytes[bank] = 0;
    ddr_pp_stage_received_bytes[bank] = 0;
    ddr_pp_contig_words[bank] = 0;
    ddr_pp_hwm_words[bank] = 0;
    ddr_pp_payload_crc32[bank] = 0;
    ddr_pp_stage_bytes[bank] = 0;
    ddr_pp_stage_open[bank] = 0;
    ddr_pp_bit_length[bank] = 0;
    ddr_pp_crc16[bank] = 0;
    ddr_pp_valid[bank] = 0;
    ddr_pp_udp_committed[bank] = 0;
    if (!ddr_pp_active) {
        ddr_pp_state = "IDLE";
        ddr_pp_error_code = 0;
    }
}

static void ddr_pp_udp_status(u16 bank, udp_ddr_pp_status_t *status)
{
    status->received_bytes = 0;
    status->first_missing_offset = 0;
    status->first_missing_length = 0;
    status->state = UDP_DDR_PP_STATE_IDLE;
    status->error = UDP_DDR_PP_ERROR_NONE;
    if (bank > 1u)
        return;
    if (ddr_pp_stage_owner[bank] == DDR_PP_STAGE_UDP) {
        status->state = UDP_DDR_PP_STATE_RECEIVING;
        status->received_bytes = ddr_pp_stage_received_bytes[bank];
        ddr_pp_udp_missing_range(bank, ddr_pp_stage_expected_bytes[bank],
                                 &status->first_missing_offset,
                                 &status->first_missing_length);
    } else if (ddr_pp_udp_committed[bank]) {
        /* Only a successful UDP commit is exposed as a UDP COMMITTED state. */
        status->state = UDP_DDR_PP_STATE_COMMITTED;
        status->received_bytes = ddr_pp_bit_length[bank] / 8u;
        status->first_missing_offset = status->received_bytes;
        status->first_missing_length = 0;
    }
}

static void ddr_pp_flush_cpu_write_range(UINTPTR addr, u32 length)
{
    Xil_DCacheFlushRange(addr, length);
}

