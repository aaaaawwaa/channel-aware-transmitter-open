/* ---- 复数 I/Q 损伤: 定点三角与矩阵合成 ---- */

/* Q1.15 定点乘 -> 指定右移, 四舍五入(符号对称, 与 host round_shift_signed 同法)。
 * 32 位中间量足够: |x|,|y| <= 32767 -> 积 <= 1.07e9。 */
static long iq_qmul(long x, long y, int shift)
{
    long p = x * y;
    if (p >= 0) return (p + (1L << (shift - 1))) >> shift;
    return -(((-p) + (1L << (shift - 1))) >> shift);
}

/* 角度(0.01 度单位)查表 + 线性插值, 返回 Q1.15。
 * 表间距 2*pi/1024, 插值误差约 (2*pi/1024)^2/8 = 4.7e-6 rad —— 折算到 Q2.14
 * 系数上约 0.08 LSB, 远低于系数本身的 1 LSB, 所以不会成为镜像抑制的瓶颈。 */
static short iq_sincos(const short *tbl, long deg100)
{
    long long pos, v0, v1;
    long frac;
    int i0, i1;

    deg100 %= 36000L;
    if (deg100 < 0) deg100 += 36000L;
    pos = ((long long)deg100 * ((long long)SINCOS_Q15_N << 16)) / 36000LL;
    i0 = (int)(pos >> 16) & (SINCOS_Q15_N - 1);
    frac = (long)(pos & 0xFFFFLL);
    i1 = (i0 + 1) & (SINCOS_Q15_N - 1);
    v0 = tbl[i0];
    v1 = tbl[i1];
    return (short)(v0 + (((v1 - v0) * frac) >> 16));
}

static long iq_clamp_q214(long v)
{
    if (v > 32767L) return 32767L;
    if (v < -32768L) return -32768L;
    return v;
}

/* Q1.15 -> Q2.14: **右移 1 位**(四舍五入)。
 * 方向容易写反: Q2.14 的小数位比 Q1.15 少一位, 同样的数值要右移, 不是乘 2。
 * 写成乘 2 会让单位阵变成 32767(= 2.0)并在大系数处到处钳位 ——
 * 离线比对(32190 组输入)正是这样抓出来的。 */
static long iq_to_q214(long v)
{
    if (v >= 0) return iq_clamp_q214((v + 1L) >> 1);
    return iq_clamp_q214(-((-v + 1L) >> 1));
}

/* R(phase) x diag(alpha,1) x E(phase_err), 与 channel.py 的展开式逐项对应:
 *   a = ct*al + st*sp ; b = -st*cp ; c = st*al - ct*sp ; d = ct*cp
 * Q1.15 乘 Q2.14 右移 14、Q1.15 乘 Q1.15 右移 15, 都先得到 Q1.15, 最后统一转 Q2.14。
 * 实测与 host 模型(双精度)最大偏差 3 LSB / 32768, 即镜像抑制地板约 -81 dB ——
 * 远低于 8-bit 信号自身的量化地板, 不是瓶颈。 */
static void iq_recompose(void)
{
    long ct = iq_sincos(sincos_q15_cos, iq_phase_deg100);
    long st = iq_sincos(sincos_q15_sin, iq_phase_deg100);
    long cp = iq_sincos(sincos_q15_cos, iq_phaseerr_deg100);
    long sp = iq_sincos(sincos_q15_sin, iq_phaseerr_deg100);
    long al = iq_gain_q14;
    long a = iq_to_q214(iq_qmul(ct, al, 14) + iq_qmul(st, sp, 15));
    long b = iq_to_q214(-iq_qmul(st, cp, 15));
    long c = iq_to_q214(iq_qmul(st, al, 14) - iq_qmul(ct, sp, 15));
    long d = iq_to_q214(iq_qmul(ct, cp, 15));

    iq_coef_ab = ((u32)(b & 0xFFFFL) << 16) | (u32)(a & 0xFFFFL);
    iq_coef_cd = ((u32)(d & 0xFFFFL) << 16) | (u32)(c & 0xFFFFL);
}

/* fword = round(delta_f / 50e6 * 2^32), 32 位全宽。必须走 long long:
 * delta_f = 1e6 时 delta_f << 32 约 4.3e15, 32 位装不下。 */
static void iq_recompute_fword(void)
{
    long long num = (long long)iq_freqoff_hz * 4294967296LL;
    long long fw;

    if (num >= 0) fw =  (num + 25000000LL) / 50000000LL;
    else          fw = -(((-num) + 25000000LL) / 50000000LL);
    iq_fword = (u32)fw;
}

